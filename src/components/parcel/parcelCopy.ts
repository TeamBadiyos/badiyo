export function useParcelCopy() {
  const { lang } = useLanguage();
  return lang === "mr" ? mr : en;
}

export function fill(s: string, vals: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vals[k] ?? ""));
}

export const rs = (n: number) => (Number.isInteger(n) ? String(n) : n.toFixed(2));
